#!/usr/bin/env python3
"""Record the retrieval-eval fixtures against a REAL embedding endpoint.

Owner-run, one-time (and again whenever the snapshot, the labels, or the
embedding model changes). NOT collected by pytest. What it does:

1. Reads the frozen library snapshot (`fixtures/library_eval_snapshot.jsonl`)
   and the owner-authored golden labels (`fixtures/library_eval.jsonl`).
   REFUSES to run if either is missing — the labels must exist first, and
   they must be written by the owner, never generated by a model
   (eval-set-construction rule: labelers independent of the system under
   test; see fixtures/LABELING.md).
2. Embeds every snapshot doc (search_document prefix) and every golden query
   (search_query prefix) against the real `/v1/embeddings` endpoint at
   $ARIA_EMBED_URL (the tailnet embedding box must be awake) and writes
   `fixtures/library_eval_vecs.npz` keyed by doc_hash / normalized query.
3. Runs the full harness (lexical / vector / hybrid, recall@10 + nDCG@10)
   on the recorded vectors and rewrites `fixtures/eval_baseline.json`.

Usage (from backend/, in a venv with requirements-dev.txt + numpy):

    ARIA_EMBED_URL=http://<embed-host>:<port>/v1/embeddings \
        python tests/record_eval_fixtures.py

Then: review the git diff of the four fixture files and commit them. The CI
gate in test_retrieval_eval.py arms automatically once they exist; any later
PR that regresses hybrid recall@10 / nDCG@10 below the committed baseline
fails CI. Never edit eval_baseline.json by hand.
"""
import json
import os
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import library_index as libindex  # noqa: E402
import eval_harness as harness  # noqa: E402


def _die(msg: str) -> "NoReturn":  # noqa: F821
    print(f"\nREFUSING TO RUN: {msg}\n", file=sys.stderr)
    sys.exit(2)


def main() -> int:
    # -- preconditions: owner-authored inputs must exist ---------------------
    if not harness.QUERIES_PATH.exists():
        _die(
            f"{harness.QUERIES_PATH} is missing.\n"
            "The golden labels are the owner's job and the whole point of "
            "this eval: write ~40 queries with relevant_track_ids per "
            "fixtures/LABELING.md (from memory of your library, BEFORE "
            "playing with the feature — never model-generated).")
    if not harness.SNAPSHOT_PATH.exists():
        _die(
            f"{harness.SNAPSHOT_PATH} is missing.\n"
            "Export the frozen library snapshot first — the sqlite3 command "
            "is in fixtures/LABELING.md.")

    snapshot = harness.load_snapshot(harness.SNAPSHOT_PATH)
    queries = harness.load_queries(harness.QUERIES_PATH)
    harness.validate_queries(queries, snapshot)
    print(f"snapshot: {len(snapshot)} tracks   golden set: "
          f"{len(queries)} queries")

    # Integrity: if the export carried doc_hash, recomposition must match —
    # catches a broken export before it poisons the recorded vectors.
    mismatched = [
        row["track_id"] for row in snapshot
        if row.get("doc_hash")
        and libindex.doc_hash(libindex.compose_doc(row)) != row["doc_hash"]
    ]
    if mismatched:
        _die(f"doc_hash round-trip failed for {len(mismatched)} tracks "
             f"(first: {mismatched[:5]}) — the snapshot export does not "
             "recompose to the indexed doc_text; fix the export before "
             "recording.")

    # -- the real embedder ---------------------------------------------------
    embedder = libindex.Embedder()  # honors $ARIA_EMBED_URL
    print(f"embedding endpoint: {embedder.url} (model {embedder.model}, "
          f"{embedder.dim}-dim)")
    if embedder.status() != "ok":
        _die(f"embedding endpoint unreachable at {embedder.url} — is the "
             "embedding box awake and llama-swap serving? Set ARIA_EMBED_URL "
             "if it is not the default.")

    # -- record doc vectors (keyed by doc_hash) ------------------------------
    docs = {}
    for row in snapshot:
        text = libindex.compose_doc(row)
        docs[libindex.doc_hash(text)] = text  # dedupe identical docs
    doc_items = sorted(docs.items())
    vectors: dict = {}
    for start in range(0, len(doc_items), libindex.EMBED_BATCH):
        chunk = doc_items[start:start + libindex.EMBED_BATCH]
        vecs = embedder.embed_batch([t for _, t in chunk],
                                    prefix=libindex.DOC_PREFIX)
        vectors.update({h: v for (h, _), v in zip(chunk, vecs)})
        print(f"  embedded docs {min(start + len(chunk), len(doc_items))}"
              f"/{len(doc_items)}", end="\r")
    print()

    # -- record query vectors (keyed by normalized query string) -------------
    keys = sorted({harness.normalize_query_key(q["query"]) for q in queries})
    for start in range(0, len(keys), libindex.EMBED_BATCH):
        chunk = keys[start:start + libindex.EMBED_BATCH]
        vecs = embedder.embed_batch(chunk, prefix=libindex.QUERY_PREFIX)
        vectors.update(dict(zip(chunk, vecs)))
    print(f"  embedded {len(keys)} query strings")

    import numpy as np
    harness.FIXTURES_DIR.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        harness.VECS_PATH,
        **{k: np.asarray(v, dtype=np.float32) for k, v in vectors.items()})
    print(f"wrote {harness.VECS_PATH} ({harness.VECS_PATH.stat().st_size:,} "
          f"bytes, {len(vectors)} vectors)")

    # -- full harness run → baseline ----------------------------------------
    result = harness.run_eval_tempdb(snapshot, queries,
                                     harness.load_vectors(harness.VECS_PATH),
                                     k=10)
    baseline = {
        mode: dict(result["modes"][mode]) for mode in harness.MODES
    }
    baseline.update({
        "recorded_at": datetime.now(timezone.utc)
                               .isoformat(timespec="seconds"),
        "snapshot_hash": harness.snapshot_file_hash(harness.SNAPSHOT_PATH),
        "n_queries": len(queries),
        "embed_model": embedder.model,
        "embed_dim": embedder.dim,
        "k": 10,
    })
    with open(harness.BASELINE_PATH, "w", encoding="utf-8") as f:
        json.dump(baseline, f, indent=2, sort_keys=True)
        f.write("\n")
    print(f"wrote {harness.BASELINE_PATH}\n")

    print(harness.format_report(result))
    print(
        "\nNext: review `git diff`/`git status` on backend/tests/fixtures/ "
        "and commit all four fixture files together. The CI gate arms on the "
        "next push. Re-run this script (deliberate, reviewed diff) whenever "
        "the snapshot, the labels, or the embedding model changes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
